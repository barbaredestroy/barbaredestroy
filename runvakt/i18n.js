var rtlLangs = ["ur"];
var RUNES_I18N = "ᚠᚢᚦᚨᚱᚲᚷᚹᚺᚾᛁᛃᛇᛈᛉᛊᛏᛒᛖᛗᛚᛜᛞᛟ";
var reduceMotionI18n = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;

function randomRuneI18n(){
  return RUNES_I18N[Math.floor(Math.random() * RUNES_I18N.length)];
}

function decodeTextI18n(el, text){
  var final = (text !== undefined) ? text : el.textContent;
  if (reduceMotionI18n){ el.textContent = final; return; }

  el.innerHTML = '';
  var words = final.split(' ');
  var chars = [];
  var spans = [];

  words.forEach(function(word, wi){
    if (word.length){
      var wrap = document.createElement('span');
      wrap.style.whiteSpace = 'nowrap';
      for (var c = 0; c < word.length; c++){
        var s = document.createElement('span');
        s.className = 'rune-char';
        s.textContent = randomRuneI18n();
        wrap.appendChild(s);
        spans.push(s);
        chars.push(word[c]);
      }
      el.appendChild(wrap);
    }
    if (wi < words.length - 1){
      el.appendChild(document.createTextNode(' '));
    }
  });

  chars.forEach(function(ch, i){
    var span = spans[i];
    var flickers = 5 + Math.floor(Math.random() * 4);
    var startDelay = i * 70;
    var flickerInterval = 80;

    for (var f = 0; f < flickers; f++){
      (function(f){
        setTimeout(function(){ span.textContent = randomRuneI18n(); }, startDelay + f * flickerInterval);
      })(f);
    }

    setTimeout(function(){
      span.textContent = ch;
      span.classList.add('settling');
      setTimeout(function(){ span.classList.remove('settling'); }, 1000);
    }, startDelay + flickers * flickerInterval);
  });
}

function decodeCascadeI18n(){
  if (reduceMotionI18n) return;
  var targets = document.querySelectorAll('.tagline, .lead, .status, .section-title span, .feature h3, .feature p, .steps h3, .steps p, .manifesto p, .legal-button, footer nav a');
  targets.forEach(function(el, idx){
    setTimeout(function(){ decodeTextI18n(el); }, idx * 90);
  });
}

function applyLangI18n(lang){
  var dict = translations[lang];
  if(!dict) return;
  var dir = rtlLangs.indexOf(lang) !== -1 ? "rtl" : "ltr";
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(function(el){
    var key = el.getAttribute('data-i18n');
    if(dict[key] !== undefined){
      el.dir = dir;
      decodeTextI18n(el, dict[key]);
    }
  });
}

document.addEventListener('DOMContentLoaded', function(){
  var langBtn = document.getElementById('langBtn');
  var langMenu = document.getElementById('langMenu');
  if (langBtn && langMenu){
    langBtn.addEventListener('click', function(e){
      e.stopPropagation();
      var open = langMenu.classList.toggle('open');
      langBtn.setAttribute('aria-expanded', open ? 'true' : 'false');
    });
    document.addEventListener('click', function(){
      langMenu.classList.remove('open');
      langBtn.setAttribute('aria-expanded', 'false');
    });
    langMenu.querySelectorAll('button').forEach(function(btn){
      btn.addEventListener('click', function(){
        applyLangI18n(btn.getAttribute('data-lang'));
        langMenu.classList.remove('open');
        langBtn.setAttribute('aria-expanded', 'false');
      });
    });
  }
  decodeCascadeI18n();
});
