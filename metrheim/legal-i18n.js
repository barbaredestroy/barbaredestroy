// ===== Effet runique : le texte apparaît d'abord en runes, puis se déchiffre =====
var RUNES_LEGAL = 'ᚠᚢᚦᚨᚱᚲᚷᚹᚺᚾᛁᛃᛇᛈᛉᛊᛏᛒᛖᛗᛚᛜᛞᛟ';
var reduceMotionLegal = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;

function randomRuneLegal(){
  return RUNES_LEGAL[Math.floor(Math.random() * RUNES_LEGAL.length)];
}

function decodeTextLegal(el, text){
  var final = (text !== undefined) ? text : el.textContent;
  if (reduceMotionLegal){ el.textContent = final; return; }

  el.innerHTML = '';
  var words = final.split(' ');
  var chars = [];
  var spans = [];

  words.forEach(function(word, wi){
    if (word.length){
      var wrap = document.createElement('span');
      wrap.style.whiteSpace = 'nowrap';
      for (var c = 0; c < word.length; c++){
        var s = document.createElement('span');
        s.className = 'rune-char';
        s.textContent = randomRuneLegal();
        wrap.appendChild(s);
        spans.push(s);
        chars.push(word[c]);
      }
      el.appendChild(wrap);
    }
    if (wi < words.length - 1){
      el.appendChild(document.createTextNode(' '));
    }
  });

  chars.forEach(function(ch, i){
    var span = spans[i];
    var flickers = 5 + Math.floor(Math.random() * 4);
    var startDelay = i * 70;
    var flickerInterval = 80;

    for (var f = 0; f < flickers; f++){
      (function(f){
        setTimeout(function(){ span.textContent = randomRuneLegal(); }, startDelay + f * flickerInterval);
      })(f);
    }

    setTimeout(function(){
      span.textContent = ch;
      span.classList.add('settling');
      setTimeout(function(){ span.classList.remove('settling'); }, 1000);
    }, startDelay + flickers * flickerInterval);
  });
}

function decodeCascadeLegal(){
  if (reduceMotionLegal) return;
  var targets = document.querySelectorAll('.legal h1, .intro, .legal article h2, .legal article p, footer nav a');
  targets.forEach(function(el, idx){
    setTimeout(function(){ decodeTextLegal(el); }, idx * 60);
  });
}

document.addEventListener('DOMContentLoaded', function(){
  var langBtn = document.getElementById('langBtn');
  var langMenu = document.getElementById('langMenu');
  langBtn.addEventListener('click', function(e){
    e.stopPropagation();
    var open = langMenu.classList.toggle('open');
    langBtn.setAttribute('aria-expanded', open ? 'true' : 'false');
  });
  document.addEventListener('click', function(){
    langMenu.classList.remove('open');
    langBtn.setAttribute('aria-expanded', 'false');
  });
  langMenu.querySelectorAll('button').forEach(function(btn){
    btn.addEventListener('click', function(){
      applyLegalLang(btn.getAttribute('data-lang'));
      langMenu.classList.remove('open');
      langBtn.setAttribute('aria-expanded', 'false');
    });
  });
  decodeCascadeLegal();
});

function applyLegalLang(lang){
  var dict = legalTranslations[lang];
  if(!dict) return;
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(function(el){
    var key = el.getAttribute('data-i18n');
    if(dict[key] !== undefined) decodeTextLegal(el, dict[key]);
  });
}
